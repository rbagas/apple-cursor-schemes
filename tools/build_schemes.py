#!/usr/bin/env python3
"""Build every colour scheme as XCursor themes and Windows cursors.

Upstream renders its SVGs to PNG bitmaps with cbmp and then builds cursors with
ctgen. This script skips that toolchain: it renders each SVG straight to the
target size with librsvg, which keeps all 14 XCursor sizes crisp, and writes the
cursor containers itself.

Requires python3, pycairo and PyGObject with librsvg (gi://Rsvg).
"""
import argparse
import io
import os
from pathlib import Path
import re
import shutil
import struct
import sys
import tomllib
import warnings

try:
    import cairo
    import gi
    gi.require_version('Rsvg', '2.0')
    from gi.repository import Rsvg
except (ImportError, ValueError) as error:  # pragma: no cover - environment guard
    raise SystemExit(f'build needs pycairo and librsvg: {error}')

sys.path.insert(0, str(Path(__file__).resolve().parent))
import wincursor
import xcursor

# Windows plays an .ani at jiffies (1/60 s). Upstream ships a 20 ms X11 delay as
# 2 jiffies in the rate chunk, so mirror that rather than the config's win_delay.
ANI_RATE = 2
# .ani frames carry one image each; Windows scales them to the chosen cursor size.
# 64 px is the middle of the Regular profile and what upstream lands on.
ANI_TARGET = 64
ROOT = Path(__file__).resolve().parent.parent
CANVAS = 256
FILL_TOKEN = '#00FF00'
OUTLINE_TOKEN = '#0000FF'
DEFAULT_CONFIG = ROOT / 'configs/x.build.toml'
WINDOWS_CONFIG = {'regular': 'configs/win_rg.build.toml',
                  'large': 'configs/win_lg.build.toml',
                  'extra-large': 'configs/win_xl.build.toml'}
# Windows reads its pointer roles in this order from the Schemes registry value.
SCHEME_ORDER = ['pointer', 'help', 'work', 'busy', 'cross', 'text', 'handwriting',
                'vert', 'horz', 'move', 'alternate', 'link', 'pin', 'person', 'pan',
                'grabbing', 'zoom-in', 'zoom-out', 'dng2', 'unavailiable', 'dng1']
ROLE_MAP = [('Arrow', 'pointer'), ('Help', 'help'), ('AppStarting', 'work'),
            ('Wait', 'busy'), ('crosshair', 'cross'), ('precisionhair', 'cross'),
            ('IBeam', 'text'), ('NWPen', 'handwriting'), ('SizeNS', 'vert'),
            ('SizeWE', 'horz'), ('Grab', 'move'), ('SizeAll', 'move'),
            ('UpArrow', 'alternate'), ('Hand', 'link'), ('Pin', 'pin'),
            ('Person', 'person'), ('Pan', 'pan'), ('Grabbing', 'grabbing'),
            ('Zoom-in', 'zoom-in'), ('Zoom-out', 'zoom-out')]

INSTALL_INF = '''; {theme}, generated by tools/build_schemes.py
; Artwork: apple_cursor v2.0.1 (GPL-3.0) https://github.com/ful1e5/apple_cursor

[Version]
signature="$CHICAGO$"
{theme}

[DefaultInstall]
CopyFiles = Scheme.Cur
AddReg    = Scheme.Reg,Wreg

[DestinationDirs]
Scheme.Cur = 10,"%CUR_DIR%"

[Scheme.Reg]
HKCU,"Control Panel\\Cursors\\Schemes","%SCHEME_NAME%",,"%SCHEME_PATHS%"

[Wreg]
HKCU,"Control Panel\\Cursors",,0x00020000,"%SCHEME_NAME%"
{role_registry}
HKLM,"SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Runonce\\Setup\\","",,"rundll32.exe shell32.dll,Control_RunDLL main.cpl @0,1"

[Scheme.Cur]
{files}

[Strings]
CUR_DIR             = "Cursors\\{scheme_dir}"
SCHEME_NAME         = "{scheme_name}"
{string_vars}
'''

UNINSTALL_BAT = '''@echo off
REM Remove the "{scheme_name}" cursor scheme installed by install.inf.
REG DELETE "HKCU\\Control Panel\\Cursors\\Schemes" /v "{scheme_name}" /f
echo Removed {scheme_name}. Open Mouse Properties to pick another scheme.
'''


def show(path):
    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


def load_toml(path):
    with open(path, 'rb') as handle:
        return tomllib.load(handle)


def parse_color(text):
    value = text.lstrip('#')
    if len(value) != 6:
        raise SystemExit(f'bad colour in schemes.toml: {text}')
    return '#%s' % value.upper()


def schemes():
    return load_toml(ROOT / 'schemes.toml')['scheme']


def cursor_specs(config):
    """Ordered cursor definitions: name, hotspot, symlinks, and SVG frame paths."""
    fallback = config['cursors']['fallback_settings']
    specs = []
    for name, entry in config['cursors'].items():
        if name == 'fallback_settings':
            continue
        pattern = entry['png']
        if '-*' in pattern:
            frames = sorted((ROOT / 'svg' / pattern.split('-*')[0]).glob('*.svg'))
        else:
            frames = [ROOT / 'svg' / (pattern[:-4] + '.svg')]
        if not frames or not all(path.is_file() for path in frames):
            raise SystemExit(f'{name}: missing SVG source for {pattern}')
        specs.append({
            'name': name,
            'frames': frames,
            'x_hotspot': entry.get('x_hotspot', fallback['x_hotspot']),
            'y_hotspot': entry.get('y_hotspot', fallback['y_hotspot']),
            'symlinks': entry.get('x11_symlinks', []),
            'windows': entry.get('win_name'),
        })
    return specs


class Renderer:
    """Renders one colour scheme; each SVG is parsed once and drawn at many sizes."""

    def __init__(self, fill, outline):
        self.fill = fill
        self.outline = outline
        self._handles = {}
        self.renders = 0

    def handle(self, path):
        handle = self._handles.get(path)
        if handle is None:
            text = path.read_text()
            text = re.sub(re.escape(FILL_TOKEN), self.fill, text, flags=re.IGNORECASE)
            text = re.sub(re.escape(OUTLINE_TOKEN), self.outline, text, flags=re.IGNORECASE)
            handle = Rsvg.Handle.new_from_data(text.encode())
            self._handles[path] = handle
        return handle

    def surface(self, path, size):
        surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, size, size)
        context = cairo.Context(surface)
        context.scale(size / CANVAS, size / CANVAS)
        # render_cairo draws in document coordinates; the scale above maps 256 -> size.
        # (render_document needs an Rsvg.Rectangle viewport, which PyGObject does not expose.)
        with warnings.catch_warnings():
            warnings.simplefilter('ignore', DeprecationWarning)
            self.handle(path).render_cairo(context)
        surface.flush()
        self.renders += 1
        return surface

    def argb(self, path, size):
        """Premultiplied 32-bit ARGB values, the layout XCursor stores."""
        surface = self.surface(path, size)
        stride = surface.get_stride()
        data = surface.get_data()
        values = []
        for row in range(size):
            offset = row * stride
            for column in range(size):
                blue, green, red, alpha = data[offset:offset + 4]
                values.append((alpha << 24) | (red << 16) | (green << 8) | blue)
                offset += 4
        return values

    def png(self, path, size):
        surface = self.surface(path, size)
        buffer = io.BytesIO()
        surface.write_to_png(buffer)
        return buffer.getvalue()


def x_hotspot(spec, size, platform):
    """Upstream formula per platform: plain floor for X11, (value-1)//256 for Windows."""
    if platform == 'windows':
        return [(axis * size - 1) // CANVAS for axis in (spec['x_hotspot'], spec['y_hotspot'])]
    return [axis * size // CANVAS for axis in (spec['x_hotspot'], spec['y_hotspot'])]


def build_linux(scheme, config, output):
    name = f"AppleCursor-{scheme['name']}"
    target = output / 'linux' / name
    if target.exists():
        shutil.rmtree(target)
    cursors = target / 'cursors'
    cursors.mkdir(parents=True)
    renderer = Renderer(parse_color(scheme['fill']), parse_color(scheme['outline']))
    sizes = config['cursors']['fallback_settings']['x11_sizes']
    delay = config['cursors']['fallback_settings']['x11_delay']
    for spec in cursor_specs(config):
        blocks = []
        for size in sizes:
            hot_x, hot_y = x_hotspot(spec, size, 'x11')
            for frame in spec['frames']:
                blocks.append((xcursor.IMAGE, size, xcursor.image(
                    size, size, size, hot_x, hot_y, delay, renderer.argb(frame, size))))
        path = cursors / spec['name']
        xcursor.write(path, [(xcursor.COMMENT, 1, xcursor.comment(
            f"{name} {spec['name']}"))] + blocks)
        for alias in spec['symlinks']:
            link = cursors / alias
            link.unlink(missing_ok=True)
            link.symlink_to(spec['name'])
    comment = f"{scheme['comment']} · apple_cursor v2.0.1 artwork"
    (target / 'index.theme').write_text(
        f'[Icon Theme]\nName={name}\nComment={comment}\nInherits="hicolor"\n')
    (target / 'cursor.theme').write_text(f'[Icon Theme]\nName={name}\nInherits="hicolor"\n')
    return target, renderer.renders


def build_windows(scheme, config, output, profile):
    name = f"AppleCursor-{scheme['name']}"
    target = output / 'windows' / name
    if target.exists():
        shutil.rmtree(target)
    target.mkdir(parents=True)
    renderer = Renderer(parse_color(scheme['fill']), parse_color(scheme['outline']))
    fallback = config['cursors']['fallback_settings']
    sizes = fallback['win_sizes']
    rate = ANI_RATE
    produced = {}
    for spec in cursor_specs(config):
        role = spec['windows']
        if role is None:
            continue
        frames = []
        for size in sizes:
            hot = x_hotspot(spec, size, 'windows')
            frames.append((size, renderer.png(spec['frames'][0], size), hot))
        if len(spec['frames']) > 1:
            # One image per frame, at a size near 64 px: Windows scales it to the
            # current cursor size, and six sizes per frame would bloat the file 4x.
            frame_size = min(sizes, key=lambda value: abs(value - ANI_TARGET))
            animated = [wincursor.cur([(frame_size, renderer.png(frame, frame_size),
                                       x_hotspot(spec, frame_size, 'windows'))])
                        for frame in spec['frames']]
            data = wincursor.ani(animated, rate=ANI_RATE)
            filename = f'{role}.ani'
        else:
            data = wincursor.cur(frames)
            filename = f'{role}.cur'
        wincursor.write(target / filename, data)
        produced[role.lower()] = filename
    write_windows_metadata(target, scheme, name, produced)
    return target, renderer.renders


def write_windows_metadata(target, scheme, name, produced):
    theme = f"{name} Cursors"
    scheme_dir = f"{name} Cursors"
    role_lines = '\n'.join(
        f'HKCU,"Control Panel\\Cursors",{role},0x00020000,"%10%\\%CUR_DIR%\\%{variable}%"'
        for role, variable in ROLE_MAP)
    files = '\n'.join(produced[variable] for variable in SCHEME_ORDER if variable in produced)
    strings = '\n'.join(f'{variable:<20} = "{filename}"'
                        for variable, filename in sorted(produced.items()))
    paths = ','.join(f'%10%\\%CUR_DIR%\\%{variable}%'
                     for variable in SCHEME_ORDER if variable in produced)
    inf = INSTALL_INF.format(theme=theme, role_registry=role_lines, files=files,
                             scheme_dir=scheme_dir, scheme_name=theme,
                             string_vars=strings).replace('%SCHEME_PATHS%', paths)
    (target / 'install.inf').write_text(inf)
    (target / 'uninstall.bat').write_text(UNINSTALL_BAT.format(scheme_name=theme))


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--scheme', action='append', default=[],
                        help='Build only this scheme (repeatable); default: all')
    parser.add_argument('--platforms', default='linux,windows',
                        help='Comma separated subset of linux,windows (default: both)')
    parser.add_argument('--output', type=Path, default=ROOT / 'dist',
                        help='Output directory (default: dist)')
    parser.add_argument('--windows-profile', choices=sorted(WINDOWS_CONFIG), default='regular',
                        help='Windows size profile (default: regular)')
    parser.add_argument('--list', action='store_true', help='List schemes and exit')
    args = parser.parse_args()

    available = schemes()
    if args.list:
        for scheme in available:
            print(f"{scheme['name']:<18} fill {scheme['fill']:<8} outline {scheme['outline']}")
        return

    wanted = [s for s in available if not args.scheme or s['name'] in args.scheme]
    unknown = set(args.scheme) - {s['name'] for s in available}
    if unknown:
        raise SystemExit(f'unknown scheme(s): {", ".join(sorted(unknown))}')
    platforms = [p.strip() for p in args.platforms.split(',') if p.strip()]
    for platform in platforms:
        if platform not in ('linux', 'windows'):
            raise SystemExit(f'unknown platform: {platform}')

    config = load_toml(DEFAULT_CONFIG)
    windows_config = load_toml(ROOT / WINDOWS_CONFIG[args.windows_profile])
    total = 0
    for scheme in wanted:
        if 'linux' in platforms:
            target, renders = build_linux(scheme, config, args.output)
            total += renders
            count = len(list((target / 'cursors').iterdir()))
            print(f'linux   {show(target)}  ({count} names, {renders} renders)')
        if 'windows' in platforms:
            target, renders = build_windows(scheme, windows_config, args.output,
                                            args.windows_profile)
            total += renders
            count = len(list(target.glob('*.cur'))) + len(list(target.glob('*.ani')))
            print(f'windows {show(target)}  ({count} cursors, {renders} renders)')
    print(f'done: {len(wanted)} scheme(s), {total} renders')


if __name__ == '__main__':
    main()
